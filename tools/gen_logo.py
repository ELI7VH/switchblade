"""The Switch Blade boot logo (run by tools/build.py generate()).

  gen_logo.py OUT.h [--src assets/switchblade_logo.jpg] [--png PREVIEW.png]

assets/switchblade_logo.jpg (the user's artwork) -> crop the black margins -> fit to 236 x 135 (Lanczos) ->
an adaptive palette of at most 128 colours, index 0 = pure black (the splash is on black, so the margin
costs nothing and has no box) -> OUT.h: 8 bpp indices and an RGB565 palette, both `const` (flash, not RAM).
The logo is artwork: the splash draws it in these colours whatever the UI palette is. Deterministic: median-cut
quantising, no dithering, no randomness; the same input gives the same bytes. Fails (exit 1) on a violated limit.
"""
import argparse
import sys
from pathlib import Path

from PIL import Image

W, H = 236, 135          # the fitted size (the splash centres it on the 240 x 240 screen)
MAXCOL = 128
BLACK_CUT = 12           # a pixel whose brightest channel is below this is the margin: pure black
SRC = Path(__file__).resolve().parent.parent / "assets" / "switchblade_logo.jpg"


def build(src):
    im = Image.open(src).convert("RGB")
    # the margins: the bbox of everything brighter than the (JPEG-noisy) black
    bbox = im.point(lambda v: 255 if v >= BLACK_CUT else 0).convert("L").getbbox()
    im = im.crop(bbox).resize((W, H), Image.LANCZOS)
    im = im.point(lambda v: 0 if v < BLACK_CUT else v)             # (the resize's ringing in the black stays black)
    q = im.quantize(colors=MAXCOL, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:3 * MAXCOL]
    raw = q.tobytes()
    n = max(raw) + 1
    cols = [tuple(pal[3 * i:3 * i + 3]) for i in range(n)]
    dark = min(range(n), key=lambda i: sum(cols[i]))               # the black: exactly black, index 0
    cols[dark] = (0, 0, 0)
    order = [dark] + [i for i in range(n) if i != dark]
    remap = {old: new for new, old in enumerate(order)}
    px = bytes(remap[v] for v in raw)
    cols = [cols[i] for i in order]
    return cols, px


def rgb565(c):
    return ((c[0] >> 3) << 11) | ((c[1] >> 2) << 5) | (c[2] >> 3)


def check(cols, px):
    assert 1 <= len(cols) <= MAXCOL, f"palette of {len(cols)} colours"
    assert cols[0] == (0, 0, 0) and rgb565(cols[0]) == 0, "index 0 is not pure black"
    assert len(px) == W * H, "pixel count"
    assert max(px) < len(cols), "an index past the palette"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--src", default=str(SRC))
    ap.add_argument("--png", help="write a preview (the quantised logo, true size)")
    a = ap.parse_args()
    cols, px = build(a.src)
    check(cols, px)
    p565 = [rgb565(c) for c in cols]
    lines = ["/* generated by tools/gen_logo.py from assets/switchblade_logo.jpg: do not edit */",
             "#ifndef UI_LOGO_H", "#define UI_LOGO_H",
             f"#define UI_LOGO_W {W}", f"#define UI_LOGO_H {H}", f"#define UI_LOGO_NCOL {len(cols)}",
             "/* RGB565 (not byte-swapped); index 0 is black */",
             f"static const uint16_t UI_LOGO_PAL[UI_LOGO_NCOL] = {{"]
    for i in range(0, len(p565), 12):
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in p565[i:i + 12]) + ",")
    lines.append("};")
    lines.append("/* 8 bpp palette indices, row by row */")
    lines.append(f"static const uint8_t UI_LOGO_PX[UI_LOGO_W * UI_LOGO_H] = {{")
    for r in range(H):
        row = px[r * W:(r + 1) * W]
        lines.append("    " + ",".join(str(v) for v in row) + ",")
    lines.append("};")
    lines.append("_Static_assert(UI_LOGO_NCOL <= 128 && UI_LOGO_W <= 240 && UI_LOGO_H <= 240, \"logo size\");")
    lines.append("#endif")
    Path(a.out).write_text("\n".join(lines) + "\n")
    if a.png:
        im = Image.new("RGB", (W, H))
        im.putdata([cols[v] for v in px])
        im.save(a.png)
    print(f"gen_logo: {W}x{H}, {len(cols)} colours, {len(px)} B of indices -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

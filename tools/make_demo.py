"""The browser emulator's demo song (web/emu/demo_song.h) from a MIDI file: a 28-bar excerpt, at most a minute, one part per track.

  tools/make_demo.py SONG.mid [OUT.h]        (needs mido; default OUT web/emu/demo_song.h)

The excerpt (bars of the source, 0-based, played back to back): 14-17 the bass alone, 18-25 the riff over the bass, 26-33 the stabs
(and the strings line), 57-64 the marimba. The parts by the source's track names:
  T1 OB-Z   SYNBASS 1                      T2 WAVE  BANDNEON, STRINGS (two octaves down)
  T3 NANO   MARIMBA                        T4 JUNO  SAW WAVE: its riff (bars 18-21) looped over the whole excerpt
Each note becomes an on and an off event at its time in milliseconds at the source's tempo; felucca_web.c (web_demo) plays them
straight into the tracks. Overlapping notes of one part keep their order; the excerpt's notes are cut at a section's end.
"""
import sys
from pathlib import Path

import mido

SECTIONS = [(14, 18), (18, 26), (26, 34), (57, 65)]
LOOP = {"SAW WAVE": (18, 22)}                    # a part whose bars b0..b1-1 repeat from the excerpt's start to its end
PARTS = {"SYNBASS 1": (0, 0), "BANDNEON": (1, 0), "STRINGS": (1, -24), "SAW WAVE": (3, 0), "MARIMBA": (2, 0)}


def demo_notes(src):
    """the excerpt's notes: ([(start tick, length, track, note, velocity)], ticks a bar, ticks in all, tempo in us a beat)"""
    m = mido.MidiFile(src)
    tpb, bar = m.ticks_per_beat, m.ticks_per_beat * 4
    tempo = next((x.tempo for t in m.tracks for x in t if x.type == "set_tempo"), 500000)
    ms_per_tick = tempo / 1000.0 / tpb
    total_ticks = sum(b1 - b0 for b0, b1 in SECTIONS) * bar
    notes = []                                   # (start tick in the excerpt, length, track, note, velocity)
    for t in m.tracks:
        if t.name not in PARTS:
            continue
        trk, shift = PARTS[t.name]
        now, held = 0, {}
        for x in t:
            now += x.time
            if x.type == "note_on" and x.velocity > 0:
                held.setdefault(x.note, []).append((now, x.velocity))
            elif x.type in ("note_off", "note_on") and held.get(x.note):
                t0, vel = held[x.note].pop(0)
                if t.name in LOOP:
                    b0, b1 = LOOP[t.name]
                    if b0 * bar <= t0 < b1 * bar:
                        ln = max(1, min(now, b1 * bar) - t0)
                        for rep in range(0, total_ticks, (b1 - b0) * bar):
                            s0 = rep + t0 - b0 * bar
                            if s0 < total_ticks:
                                notes.append((s0, min(ln, total_ticks - s0), trk, x.note + shift, vel))
                    continue
                base = 0
                for b0, b1 in SECTIONS:
                    if b0 * bar <= t0 < b1 * bar:
                        end = min(now, b1 * bar)
                        notes.append((base + t0 - b0 * bar, max(1, end - t0), trk, x.note + shift, vel))
                        break
                    base += (b1 - b0) * bar
    return notes, bar, total_ticks, tempo


def main():
    src = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / "web" / "emu" / "demo_song.h"
    notes, bar, total_ticks, tempo = demo_notes(src)
    ms_per_tick = tempo / 1000.0 / (bar // 4)
    ev = []
    for s, ln, trk, note, vel in notes:
        ev.append((round(s * ms_per_tick), 1, trk, note, vel))
        ev.append((round((s + ln) * ms_per_tick) - 1, 0, trk, note, 0))   # (an off a millisecond early: a repeat of the note is a new attack)
    ev.sort(key=lambda e: (e[0], e[1]))         # (at one time, the offs first)
    total = total_ticks * ms_per_tick
    H = [f"/* generated by tools/make_demo.py from {src.name}: do not edit. {len(notes)} notes, {total / 1000:.1f} s at "
         f"{60000000 / tempo:.0f} BPM; T1 bass, T2 strings, T3 keys, T4 synth */",
         f"#define DEMO_BPM {round(60000000 / tempo)}",
         f"#define DEMO_MS {round(total)}",
         "static const struct { uint32_t ms; uint8_t trk, note, vel; } DEMO_EV[] = {   /* vel 0: the note's off */"]
    H += [f"    {{{e[0]}, {e[2]}, {e[3]}, {e[4]}}}," for e in ev]
    H.append("};")
    out.write_text("\n".join(H) + "\n")
    print(f"make_demo: {len(notes)} notes, {len(ev)} events, {total / 1000:.1f} s -> {out}")


if __name__ == "__main__":
    main()
